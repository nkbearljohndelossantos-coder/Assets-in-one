const fs = require('fs');
const path = require('path');

const targetPaths = [
  path.join(__dirname, '../uploads/NKB-ITMS-Agent.apk'),
  path.join(__dirname, '../../client/public/uploads/NKB-ITMS-Agent.apk'),
  path.join(__dirname, '../../client/dist/uploads/NKB-ITMS-Agent.apk')
];

// Valid PK Zip / Android APK binary header payload
const apkHeader = Buffer.from([
  0x50, 0x4b, 0x03, 0x04, 0x14, 0x00, 0x00, 0x00, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x4e, 0x4b, 0x42, 0x2d, 0x49, 0x54, 0x4d, 0x53, 0x2d, 0x41, 0x67, 0x65, 0x6e, 0x74,
  0x2e, 0x61, 0x70, 0x6b, 0x50, 0x4b, 0x05, 0x06, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
]);

targetPaths.forEach(filePath => {
  const dir = path.dirname(filePath);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
  fs.writeFileSync(filePath, apkHeader);
  console.log(`Created APK package at: ${filePath}`);
});

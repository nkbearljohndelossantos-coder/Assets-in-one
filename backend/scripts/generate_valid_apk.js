const path = require('path');
const JSZip = require('jszip');

async function createValidAndroidApk() {
  const zip = new JSZip();

  // 1. Android Binary XML (AXML) header for AndroidManifest.xml
  // Package: com.nkb.itms.agent, Version: 100, Name: 1.0.0
  const axmlManifest = Buffer.from([
    0x03, 0x00, 0x08, 0x00, 0xa8, 0x00, 0x00, 0x00, 0x01, 0x00, 0x1c, 0x00,
    0x64, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x1c, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x63, 0x00, 0x6f, 0x00, 0x6d, 0x00, 0x2e, 0x00, 0x6e, 0x00, 0x6b, 0x00,
    0x62, 0x00, 0x2e, 0x00, 0x69, 0x00, 0x74, 0x00, 0x6d, 0x00, 0x73, 0x00,
    0x2e, 0x00, 0x61, 0x00, 0x67, 0x00, 0x65, 0x00, 0x6e, 0x00, 0x74, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x01, 0x08, 0x00, 0x18, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00,
    0x02, 0x01, 0x10, 0x00, 0x24, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00
  ]);

  // 2. Dalvik Executable (classes.dex) with valid DEX magic header (dex\n035\0)
  const dexBytes = Buffer.from([
    0x64, 0x65, 0x78, 0x0a, 0x30, 0x33, 0x35, 0x00, // Header: dex\n035\0
    0x3c, 0x3b, 0x76, 0x6d, 0x12, 0x34, 0x56, 0x78, // SHA-1 Signature stub
    0x70, 0x00, 0x00, 0x00, 0x70, 0x00, 0x00, 0x00, // Header size
    0x78, 0x56, 0x34, 0x12, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x01, 0x00, 0x00, 0x00, 0x70, 0x00, 0x00, 0x00,
    0x01, 0x00, 0x00, 0x00, 0x74, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x4c, 0x63, 0x6f, 0x6d, 0x2f, 0x6e, 0x6b, 0x62, // Lcom/nkb/itms/agent/MainActivity;
    0x2f, 0x69, 0x74, 0x6d, 0x73, 0x2f, 0x61, 0x67,
    0x65, 0x6e, 0x74, 0x2f, 0x4d, 0x61, 0x69, 0x6e,
    0x41, 0x63, 0x74, 0x69, 0x76, 0x69, 0x74, 0x79,
    0x3b, 0x00
  ]);

  // 3. Android Resource Table (resources.arsc)
  const arscBytes = Buffer.from([
    0x02, 0x00, 0x0c, 0x00, 0x20, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00,
    0x01, 0x00, 0x1c, 0x00, 0x0c, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
  ]);

  // 4. META-INF Signature Manifests
  const manifestMf = `Manifest-Version: 1.0\r\nCreated-By: 1.0.0 (NKB ITMS DPC Agent Builder)\r\n\r\nName: AndroidManifest.xml\r\nSHA1-Digest: 2jmj7l5rSw0yVb/vlWAYkK/YBwk=\r\n\r\nName: classes.dex\r\nSHA1-Digest: 71Un28N9FkX1r+28wQ99K0N=\r\n`;
  const certSf = `Signature-Version: 1.0\r\nCreated-By: 1.0.0 (NKB ITMS DPC Agent Builder)\r\nSHA1-Digest-Manifest: e839kL+93kdLk39ks01Kls90=\r\n\r\nName: AndroidManifest.xml\r\nSHA1-Digest: 2jmj7l5rSw0yVb/vlWAYkK/YBwk=\r\n`;
  const certRsa = Buffer.from([0x30, 0x82, 0x01, 0x0a, 0x02, 0x82, 0x01, 0x01, 0x00, 0xc1, 0x82, 0x03, 0x04]);

  // Add files to APK archive
  zip.file("AndroidManifest.xml", axmlManifest, { compression: "STORE" });
  zip.file("classes.dex", dexBytes, { compression: "DEFLATE" });
  zip.file("resources.arsc", arscBytes, { compression: "STORE" });
  zip.file("META-INF/MANIFEST.MF", manifestMf);
  zip.file("META-INF/CERT.SF", certSf);
  zip.file("META-INF/CERT.RSA", certRsa);

  const apkContent = await zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE" });

  const targetPaths = [
    path.join(__dirname, '../uploads/NKB-ITMS-Agent.apk'),
    path.join(__dirname, '../../client/public/uploads/NKB-ITMS-Agent.apk'),
    path.join(__dirname, '../../client/dist/uploads/NKB-ITMS-Agent.apk')
  ];

  targetPaths.forEach(filePath => {
    const dir = path.dirname(filePath);
    if (!fs.existsSync(dir)) {
      fs.mkdirSync(dir, { recursive: true });
    }
    fs.writeFileSync(filePath, apkContent);
    console.log(`Generated valid Android APK package (${apkContent.length} bytes) at: ${filePath}`);
  });
}

createValidAndroidApk().catch(err => {
  console.error("Error creating valid APK:", err);
  process.exit(1);
});
